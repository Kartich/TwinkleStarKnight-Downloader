# -*- coding: utf-8 -*-
"""Spine global-action injection engine, integrated into Smart Bundle Downloader.

Only processes SKEL files whose path identifies an SD/CH Spine asset.
The rebuilt SKEL is generated by SpineSkeletonDataConverter, the original file is
backed up, and the rebuilt SKEL replaces the original when enabled.
"""
from __future__ import annotations

import json
import math
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path, PurePosixPath
from typing import Callable, Iterable


def _num(value):
    value = float(value)
    return int(value) if value.is_integer() else round(value, 6)


DIRECTIONS = ["上", "下", "左", "右", "左上", "右上", "左下", "右下"]


def _direction_vector(direction):
    return {
        "上": (0.0, 1.0), "下": (0.0, -1.0), "左": (-1.0, 0.0), "右": (1.0, 0.0),
        "左上": (-0.7071068, 0.7071068), "右上": (0.7071068, 0.7071068),
        "左下": (-0.7071068, -0.7071068), "右下": (0.7071068, -0.7071068),
    }.get(str(direction), (0.0, 1.0))


def _profile(duration, amp, count, direction, points):
    duration = max(.001, float(duration)); count = max(1, int(count)); step = duration / count
    dx, dy = _direction_vector(direction)
    out = [{"time": 0, "x": 0, "y": 0}]
    for i in range(count):
        start = i * step
        for pos, value in points[1:]:
            magnitude = float(amp) * float(value)
            out.append({"time": _num(start + step * pos), "x": _num(dx * magnitude), "y": _num(dy * magnitude)})
    out[-1] = {"time": _num(duration), "x": 0, "y": 0}
    return out


def keys_jump(duration, amp, count, direction="上"):
    return _profile(duration, amp, count, direction, [(0, 0), (.18, .38), (.50, 1), (.78, .42), (1, 0)])


def keys_sigh(duration, amp, count, direction="下"):
    duration = max(.001, float(duration)); count = max(1, int(count)); step = duration / count
    dx, dy = _direction_vector(direction)
    out = [{"time": 0, "x": 0, "y": 0}]
    for i in range(count):
        start = i * step
        for pos, value in ((.24, .35), (.48, 1), (.68, 1), (1, 0)):
            magnitude = float(amp) * value
            out.append({"time": _num(start + step * pos), "x": _num(dx * magnitude), "y": _num(dy * magnitude)})
    out[-1] = {"time": _num(duration), "x": 0, "y": 0}
    return out


def keys_sway(duration, amp, count, direction="右"):
    return _profile(duration, amp, count, direction, [(0, 0), (.25, 1), (.50, 0), (.75, -1), (1, 0)])


def keys_bob(duration, amp, count, direction="上"):
    return _profile(duration, amp, count, direction, [(0, 0), (.20, 1), (.50, 0), (.75, -.35), (1, 0)])


def keys_shake(duration, amp, count, direction="右"):
    return _profile(duration, amp, count, direction, [(0, 0), (.20, 1), (.40, -1), (.60, .65), (.80, -.65), (1, 0)])


def _repeat_keys(keys, repeat):
    repeat = max(1, int(repeat or 1))
    if repeat == 1:
        return [dict(k) for k in keys]
    base = sorted((dict(k) for k in keys), key=lambda k: float(k.get("time", 0)))
    if len(base) < 2:
        raise ValueError("动作至少需要两个关键帧。")
    cycle = float(base[-1].get("time", 0))
    if cycle <= 0:
        raise ValueError("动作最后一个关键帧时间必须大于 0。")
    out = []
    for rep in range(repeat):
        offset = rep * cycle
        for key in base:
            if rep > 0 and abs(float(key.get("time", 0))) < 1e-9:
                continue
            out.append({"time": _num(offset + float(key.get("time", 0))), "x": _num(key.get("x", 0)), "y": _num(key.get("y", 0))})
    return out


FACT = {
    "跳跃": keys_jump,
    "叹气": keys_sigh,
    "左右摇摆": keys_sway,
    "上下弹动": keys_bob,
    "左右抖动": keys_shake,
}
ACTION_TYPES = list(FACT) + ["自定义"]


def sync_action_type_template(action: dict, previous_kind: str) -> dict:
    """Synchronize editable keyframe data when the action type actually changes.

    A type is a template selector, not merely a label. Switching between built-in
    types imports that type's keyframe template using the row's current parameters.
    Selecting ``自定义`` preserves the currently edited keys. Re-applying the same
    type deliberately preserves manual edits; callers can use FACT[kind] explicitly
    for the separate "apply preset" command.
    """
    result = dict(action)
    kind = str(result.get("kind", "自定义"))
    previous_kind = str(previous_kind or "")
    if kind == previous_kind:
        return result
    if kind in FACT:
        duration = float(result.get("dur", 0.2))
        amplitude = float(result.get("amp", 48))
        count = int(result.get("count", 1))
        direction = str(result.get("direction", "上"))
        if not math.isfinite(duration) or duration <= 0:
            raise ValueError("动作时长必须是大于 0 的有限数值。")
        if not math.isfinite(amplitude):
            raise ValueError("动作幅度必须是有限数值。")
        if count <= 0:
            raise ValueError("动作次数必须大于 0。")
        if direction not in DIRECTIONS:
            raise ValueError(f"动作方向无效：{direction}")
        keys = FACT[kind](duration, amplitude, count, direction)
        if len(keys) < 2:
            raise ValueError(f"类型【{kind}】没有生成有效关键帧模板。")
        result["segments"] = keys
        result["dur"] = float(keys[-1]["time"])
    # Custom is a mode for manual editing: it changes no existing keyframe data.
    return result


DEFAULT_ACTIONS = [
    {"name": "Jump", "kind": "跳跃", "dur": 0.2, "amp": 48, "count": 1, "repeat": 1, "direction": "上", "segments": []},
    {"name": "DoubleJump", "kind": "跳跃", "dur": 0.4, "amp": 48, "count": 2, "repeat": 1, "direction": "上", "segments": []},
    {"name": "Sway", "kind": "左右摇摆", "dur": 0.4, "amp": 22, "count": 1, "repeat": 1, "direction": "右", "segments": []},
]

# Deliberately strict: `chara` and unrelated words beginning with "ch" are not
# enough. We need an SD/CH identifier, e.g. ch_1077004.skel or sd-123.skel.
_TARGET_TOKEN = re.compile(r"(?i)^(?:sd|ch)(?:[_-]|\d|$)")


def is_sd_ch_spine(path) -> bool:
    # Normalize separators so Windows paths remain testable from other hosts.
    p = PurePosixPath(str(path).replace("\\", "/"))
    if p.suffix.casefold() != ".skel" or p.stem.casefold().endswith("_with_actions"):
        return False
    for part in reversed(p.parts):
        stem = PurePosixPath(part).stem
        if _TARGET_TOKEN.match(stem):
            return True
    return False


def scan_target_skel_files(source_root, output_root=None) -> list[Path]:
    root = Path(source_root).expanduser().resolve()
    if not root.is_dir():
        raise FileNotFoundError(f"Spine 扫描目录不存在：{root}")
    out_root = Path(output_root).expanduser().resolve() if output_root else None
    results = []
    for path in root.rglob("*.skel"):
        try:
            resolved = path.resolve()
            if out_root and (resolved == out_root or out_root in resolved.parents):
                continue
        except OSError:
            pass
        if path.stem.casefold().endswith("_with_actions"):
            continue
        if is_sd_ch_spine(path):
            results.append(path)
    return sorted(set(results), key=lambda x: str(x).casefold())


def _run_converter(exe: Path, src: Path, dst: Path, remove_curve: bool) -> tuple[int, str]:
    cmd = [str(exe), str(src), str(dst)]
    if remove_curve:
        cmd.append("--remove-curve")
    proc = subprocess.run(
        cmd, capture_output=True, text=True, encoding="utf-8", errors="replace",
        creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
    )
    return proc.returncode, (proc.stdout or "") + "\n" + (proc.stderr or "")


def _detect_root(data: dict) -> str:
    for bone in data.get("bones", []) or []:
        if isinstance(bone, dict) and bone.get("name") and not bone.get("parent"):
            return str(bone["name"])
    return "root"


def _inject(data: dict, actions: list[dict], root_name: str) -> list[str]:
    animations = data.setdefault("animations", {})
    if not isinstance(animations, dict):
        raise ValueError("转换后的 JSON 中 animations 不是对象，无法安全注入全局动作。")
    bones = data.get("bones", []) or []
    bone_names = {str(x.get("name")) for x in bones if isinstance(x, dict) and x.get("name")}
    if bone_names and root_name not in bone_names:
        raise ValueError(f"Root 骨骼 {root_name!r} 不存在；可用骨骼示例：{', '.join(sorted(bone_names)[:12])}")
    added = []
    for action in actions:
        name = str(action.get("name", "")).strip() or "Action"
        kind = str(action.get("kind", "跳跃"))
        if kind not in ACTION_TYPES:
            raise ValueError(f"不支持的动作类型：{kind}")
        duration = float(action.get("dur", .2))
        amplitude = float(action.get("amp", 48))
        count = int(action.get("count", 1))
        repeat = int(action.get("repeat", 1))
        direction = str(action.get("direction", "上"))
        if duration <= 0 or count <= 0 or repeat <= 0:
            raise ValueError(f"动作 {name} 的时长、次数和重复次数必须大于 0。")
        if direction not in DIRECTIONS:
            raise ValueError(f"动作 {name} 的方向无效：{direction}")
        # Treat the editable keyframe list as the source of truth, as in the original
        # Spine Global Action Tool. Preset buttons create/update these segments; export
        # must not silently regenerate them and discard manual edits.
        custom = action.get("segments", [])
        if isinstance(custom, str):
            try:
                custom = json.loads(custom or "[]")
            except json.JSONDecodeError as exc:
                raise ValueError(f"动作 {name} 的关键帧 JSON 无效：{exc}") from exc
        if isinstance(custom, list) and len(custom) >= 2:
            keys = []
            for index, segment in enumerate(custom, 1):
                if not isinstance(segment, dict):
                    raise ValueError(f"动作 {name} 的第 {index} 个关键帧必须是对象。")
                keys.append({
                    "time": float(segment.get("time", segment.get("Time", 0))),
                    "x": float(segment.get("x", segment.get("X", 0))),
                    "y": float(segment.get("y", segment.get("Y", 0))),
                })
            previous = -1.0
            for index, key in enumerate(keys, 1):
                if not all(math.isfinite(key[field]) for field in ("time", "x", "y")):
                    raise ValueError(f"动作 {name} 的第 {index} 个关键帧含有无效数值。")
                if key["time"] < 0 or key["time"] <= previous:
                    raise ValueError(f"动作 {name} 的关键帧时间必须非负且严格递增（第 {index} 个）。")
                previous = key["time"]
            if previous <= 0:
                raise ValueError(f"动作 {name} 的最后一个关键帧时间必须大于 0。")
        elif kind in FACT:
            # Backward compatibility with older config.json files whose preset actions
            # did not yet serialize their generated keyframes.
            keys = FACT[kind](duration, amplitude, count, direction)
        else:
            raise ValueError(f"自定义动作 {name} 至少需要两个关键帧。")
        keys = _repeat_keys(keys, repeat)
        base = name
        suffix = 2
        while name in animations:
            name = f"{base}_EX{suffix}"
            suffix += 1
        animations[name] = {"bones": {root_name: {"translate": keys}}}
        added.append(name)
    return added


def process_one(
    skel_path,
    source_root,
    output_root,
    converter_path,
    actions: list[dict],
    *,
    root_bone: str = "",
    make_skel: bool = False,
    remove_curve: bool = False,
    keep_json: bool = False,
    backup: bool = False,
    log: Callable[[str], None] | None = None,
) -> dict:
    """Inject global actions into one target SKEL and return output paths."""
    def say(msg):
        if log:
            log(msg)

    src = Path(skel_path).expanduser().resolve()
    if not src.is_file():
        raise FileNotFoundError(f"SKEL 文件不存在：{src}")
    if not is_sd_ch_spine(src):
        raise ValueError(f"目标限制：只处理 SD / CH Spine 的 .skel 文件：{src.name}")
    exe = Path(converter_path).expanduser().resolve()
    if not exe.is_file():
        raise FileNotFoundError(f"SpineSkeletonDataConverter.exe 不存在：{exe}")
    if not actions:
        raise ValueError("至少需要配置一个全局动作。")

    root = Path(source_root).expanduser().resolve() if source_root else src.parent
    out_root = Path(output_root).expanduser().resolve()
    try:
        rel = src.relative_to(root)
    except ValueError:
        rel = Path(src.name)
    target_dir = out_root / rel.parent
    target_dir.mkdir(parents=True, exist_ok=True)
    json_out = target_dir / (src.stem + ".json")

    fd, tmp_name = tempfile.mkstemp(prefix=src.stem + "_convert_", suffix=".json", dir=str(target_dir))
    os.close(fd)
    tmp_json = Path(tmp_name)
    try:
        say(f"[转换] {src}")
        code, output = _run_converter(exe, src, tmp_json, remove_curve)
        if code or not tmp_json.is_file():
            raise RuntimeError(f"SKEL 转 JSON 失败，converter exit={code}\n{output[-2500:]}")
        try:
            data = json.loads(tmp_json.read_text(encoding="utf-8-sig"))
        except Exception as exc:
            raise RuntimeError(f"无法解析 Converter JSON：{exc}\n{output[-1500:]}") from exc
        if not isinstance(data, dict):
            raise ValueError("转换结果 JSON 根节点不是对象。")
        chosen_root = str(root_bone or "").strip() or _detect_root(data)
        names = _inject(data, actions, chosen_root)
        # JSON is only a transition file. Write it beside the temporary converter
        # file and remove it after rebuilding SKEL unless explicitly requested.
        json_out = tmp_json
        json_out.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
        say(f"[动作注入完成] Root={chosen_root} | 动作={', '.join(names)}")

        raw_json = None
        if keep_json:
            raw_json = target_dir / (src.stem + "_converter_raw.json")
            shutil.copy2(tmp_json, raw_json)
            say(f"[保留中间 JSON] {raw_json}")

        skel_out = None
        rebuild_log = ""
        if make_skel:
            # Rebuild to a temporary SKEL first. Only after conversion succeeds
            # rename the original SKEL as backup and replace it.
            skel_out = src.with_name(src.stem + "_new.skel")
            code, rebuild_log = _run_converter(exe, json_out, skel_out, remove_curve)
            if code or not skel_out.is_file():
                raise RuntimeError(f"JSON 已生成，但重新编译 SKEL 失败，converter exit={code}\n{rebuild_log[-2500:]}")

            backup_path = src.with_name(src.stem + "_backup.skel")
            if backup_path.exists():
                backup_path.unlink()

            # Keep the original file as backup only after the new SKEL is valid.
            shutil.move(str(src), str(backup_path))
            say(f"[备份 SKEL] {backup_path}")

            # Move rebuilt SKEL into the original location.
            shutil.move(str(skel_out), str(src))
            say(f"[替换 SKEL] {src}")
            skel_out = src

        return {"source": src, "json": json_out, "skel": skel_out, "raw_json": raw_json, "actions": names}
    finally:
        try:
            tmp_json.unlink(missing_ok=True)
        except OSError:
            pass


def run_batch(
    files: Iterable[Path], source_root, output_root, converter_path, actions: list[dict], *,
    root_bone="", make_skel=False, remove_curve=False, keep_json=False, backup=False,
    log: Callable[[str], None] | None = None,
) -> dict:
    """Run an action batch, logging per-file failures and continuing."""
    sources = list(files)
    ok = 0
    failed = 0
    errors = []
    for i, src in enumerate(sources, 1):
        if log:
            log(f"[{i}/{len(sources)}] {Path(src).name}")
        try:
            process_one(src, source_root, output_root, converter_path, actions,
                        root_bone=root_bone, make_skel=make_skel,
                        remove_curve=remove_curve, keep_json=keep_json,
                        backup=backup, log=log)
            ok += 1
        except Exception as exc:
            failed += 1
            msg = f"[失败] {Path(src).name}: {type(exc).__name__}: {exc}"
            errors.append(msg)
            if log:
                log(msg)
    summary = {"total": len(sources), "ok": ok, "failed": failed, "errors": errors}
    if log:
        log(f"[全局动作完成] 成功 {ok}/{len(sources)}，失败 {failed}；输出：{Path(output_root).resolve()}")
    return summary
